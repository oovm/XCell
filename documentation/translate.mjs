function convertChar(char) {
    return simplifiedMap[char] || char;
}

function convertText(text) {
    let result = text;
    for (const [simplified, traditional] of Object.entries(terminologyMap)) {
        result = result.split(simplified).join(traditional);
    }
    result = result.split('').map(convertChar).join('');
    return result;
}

function ensureDirectoryExists(filePath) {
    const dir = path.dirname(filePath);
    if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
    }
}

function translateFile(relativePath) {
    const sourcePath = path.join(sourceDir, relativePath);
    const targetPath = path.join(targetDir, relativePath);
    
    if (!fs.existsSync(sourcePath)) {
        console.log(`Source file not found: ${sourcePath}`);
        return false;
    }
    
    const content = fs.readFileSync(sourcePath, 'utf-8');
    const translatedContent = convertText(content);
    
    ensureDirectoryExists(targetPath);
    fs.writeFileSync(targetPath, translatedContent, 'utf-8');
    
    console.log(`Translated: ${relativePath}`);
    return true;
}

